using Mutagen.Bethesda;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Plugins.Cache;
using Mutagen.Bethesda.Plugins.Records;
using Mutagen.Bethesda.Skyrim;
using Mutagen.Bethesda.Synthesis;

namespace KatanaTwoHandedPatcher;

public static class Program
{
    private const string OutputPlugin = "KatanaTwoHandedPatch.esp";
    private const string KatanaKeywordEditorId = "KWA_WeapTypeKatana2H";

    private static readonly FormKey OneHandSwordKeyword = FormKey.Factory("01E711:Skyrim.esm");
    private static readonly FormKey TwoHandSwordKeyword = FormKey.Factory("06D931:Skyrim.esm");
    private static readonly FormKey BothHandsEquipType = FormKey.Factory("013F45:Skyrim.esm");

    private static readonly HashSet<FormKey> KnownKatanas =
    [
        FormKey.Factory("03AEB9:Skyrim.esm"), // Blades Sword
        FormKey.Factory("0C1989:Skyrim.esm"), // Bolar's Oathblade
        FormKey.Factory("0F1AC1:Skyrim.esm"), // Dragonbane, lowest tier
        FormKey.Factory("0F71CD:Skyrim.esm"),
        FormKey.Factory("0F71CE:Skyrim.esm"),
        FormKey.Factory("0F71CF:Skyrim.esm"),
        FormKey.Factory("0F71D0:Skyrim.esm"), // Dragonbane, highest tier
        FormKey.Factory("04A38F:Skyrim.esm"), // Ebony Blade (display/early form)
        FormKey.Factory("0EA29C:Skyrim.esm"), // Ebony Blade (real form)
        FormKey.Factory("014555:Dawnguard.esm"), // Akaviri Sword
        FormKey.Factory("0067CF:Dawnguard.esm"), // Harkon's Sword
        FormKey.Factory("000D61:ccbgssse005-goldbrand.esl"), // Goldbrand
        FormKey.Factory("000C92:ccbgssse013-dawnfang.esl"), // Bloodthirst
        FormKey.Factory("000D63:ccbgssse013-dawnfang.esl"), // Dawnfang / Duskfang
    ];

    private static readonly string[] StrongKatanaTokens =
    [
        "katana",
        "nodachi",
        "odachi",
        "uchigatana",
        "nagamaki",
        "tsurugi",
        "dai-katana",
        "daikatana",
    ];

    private static readonly Dictionary<ushort, ushort> TierDamage = new()
    {
        [7] = 12,
        [8] = 14,
        [9] = 15,
        [10] = 16,
        [11] = 16,
        [12] = 17,
        [13] = 18,
        [14] = 20,
        [15] = 21,
    };

    private static Lazy<Settings> _settings = null!;

    public static async Task<int> Main(string[] args)
    {
        if (args.SequenceEqual(["self-test"], StringComparer.OrdinalIgnoreCase))
        {
            return RunSelfTest();
        }

        return await SynthesisPipeline.Instance
            .SetAutogeneratedSettings("Settings", "settings.json", out _settings)
            .AddPatch<ISkyrimMod, ISkyrimModGetter>(RunPatch)
            .SetTypicalOpen(GameRelease.SkyrimSE, OutputPlugin)
            .Run(args);
    }

    private static void RunPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
    {
        var settings = _settings.Value;
        ValidateSettings(settings);
        state.PatchMod.ModHeader.Flags |= SkyrimModHeader.HeaderFlag.Small;

        var includes = ParseFormKeys(settings.ForceInclude, nameof(settings.ForceInclude));
        var excludes = ParseFormKeys(settings.Exclude, nameof(settings.Exclude));

        // Creating this first makes its local FormID deterministic (000800 in a
        // conventional, non-ESL patch), which is useful to OAR/IED conditions.
        var katanaKeyword = state.PatchMod.Keywords.AddNew(KatanaKeywordEditorId);

        var changed = 0;
        foreach (var weapon in state.LoadOrder.PriorityOrder.Weapon().WinningOverrides())
        {
            if (excludes.Contains(weapon.FormKey) ||
                !ShouldPatch(weapon, state.LinkCache, includes))
            {
                continue;
            }

            if (weapon.BasicStats is null || weapon.Data is null)
            {
                Console.WriteLine($"SKIP {weapon.FormKey}: missing weapon stats/data");
                continue;
            }

            var patched = state.PatchMod.Weapons.GetOrAddAsOverride(weapon);
            var originalDamage = weapon.BasicStats.Damage;
            var normalizedDamage = NormalizeDamage(originalDamage);

            patched.BasicStats!.Damage = normalizedDamage;
            patched.Data!.AnimationType = WeaponAnimationType.TwoHandSword;
            patched.Data.Skill = Skill.TwoHanded;
            patched.Data.Speed = settings.Speed;
            patched.Data.Reach = settings.Reach;
            patched.Data.Stagger = settings.Stagger;
            patched.EquipmentType.SetTo(BothHandsEquipType);

            if (patched.Critical is not null)
            {
                patched.Critical.Damage = (ushort)Math.Max(1, normalizedDamage / 2);
            }

            patched.Keywords ??= [];
            for (var i = patched.Keywords.Count - 1; i >= 0; --i)
            {
                if (patched.Keywords[i].FormKey == OneHandSwordKeyword)
                {
                    patched.Keywords.RemoveAt(i);
                }
            }

            AddKeywordIfMissing(patched.Keywords, TwoHandSwordKeyword);
            AddKeywordIfMissing(patched.Keywords, katanaKeyword.FormKey);

            changed++;
            Console.WriteLine(
                $"PATCH {weapon.FormKey} | {weapon.EditorID} | {weapon.Name?.String} | " +
                $"damage {originalDamage}->{normalizedDamage}, speed {settings.Speed:0.00}");
        }

        Console.WriteLine($"Patched {changed} two-handed katana record(s).");
        Console.WriteLine($"Animation/placement keyword: {katanaKeyword.FormKey}");
    }

    public static ushort NormalizeDamage(ushort originalDamage)
    {
        if (TierDamage.TryGetValue(originalDamage, out var tierDamage))
        {
            return tierDamage;
        }

        // Outside Skyrim's normal sword tiers, retain a consistent 40% two-hand
        // premium without ever weakening unusually strong mod-added weapons.
        var scaled = (int)Math.Round(originalDamage * 1.4, MidpointRounding.AwayFromZero);
        return (ushort)Math.Clamp(Math.Max(originalDamage, scaled), 1, ushort.MaxValue);
    }

    private static int RunSelfTest()
    {
        var expected = new Dictionary<ushort, ushort>
        {
            [7] = 12,
            [8] = 14,
            [9] = 15,
            [10] = 16,
            [11] = 16,
            [12] = 17,
            [13] = 18,
            [14] = 20,
            [15] = 21,
            [20] = 28,
        };

        foreach (var (input, output) in expected)
        {
            var actual = NormalizeDamage(input);
            if (actual != output)
            {
                Console.Error.WriteLine($"FAIL damage {input}: expected {output}, got {actual}");
                return 2;
            }
        }

        ValidateSettings(new Settings());
        Console.WriteLine($"PASS {expected.Count} damage cases and default setting bounds");
        return 0;
    }

    private static bool ShouldPatch(
        IWeaponGetter weapon,
        ILinkCache linkCache,
        IReadOnlySet<FormKey> includes)
    {
        if (includes.Contains(weapon.FormKey) || KnownKatanas.Contains(weapon.FormKey))
        {
            return true;
        }

        if (weapon.Data?.AnimationType is not
            (WeaponAnimationType.OneHandSword or WeaponAnimationType.TwoHandSword))
        {
            return false;
        }

        if (HasStrongToken(weapon.EditorID) ||
            HasStrongToken(weapon.Name?.String) ||
            HasStrongToken(weapon.Model?.File?.ToString()))
        {
            return true;
        }

        // A few Akaviri weapons have generic names but use Bethesda's katana mesh.
        if (string.Equals(
                NormalizePath(weapon.Model?.File?.ToString()),
                "weapons/akaviri/bladessword.nif",
                StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        foreach (var keywordLink in weapon.Keywords ?? [])
        {
            if (linkCache.TryResolve<IKeywordGetter>(keywordLink.FormKey, out var keyword) &&
                HasStrongToken(keyword.EditorID))
            {
                return true;
            }
        }

        return false;
    }

    private static void AddKeywordIfMissing(
        IList<IFormLinkGetter<IKeywordGetter>> keywords,
        FormKey keyword)
    {
        if (keywords.Any(x => x.FormKey == keyword))
        {
            return;
        }

        keywords.Add(new FormLink<IKeywordGetter>(keyword));
    }

    private static bool HasStrongToken(string? text)
    {
        if (string.IsNullOrWhiteSpace(text))
        {
            return false;
        }

        return StrongKatanaTokens.Any(token =>
            text.Contains(token, StringComparison.OrdinalIgnoreCase));
    }

    private static string NormalizePath(string? path) =>
        (path ?? string.Empty).Replace('\\', '/').TrimStart('/');

    private static HashSet<FormKey> ParseFormKeys(IEnumerable<string> values, string settingName)
    {
        var result = new HashSet<FormKey>();
        foreach (var value in values.Where(x => !string.IsNullOrWhiteSpace(x)))
        {
            try
            {
                result.Add(FormKey.Factory(value.Trim()));
            }
            catch (Exception ex)
            {
                throw new InvalidDataException(
                    $"Invalid {settingName} entry '{value}'. Expected FormID:PluginName.", ex);
            }
        }

        return result;
    }

    private static void ValidateSettings(Settings settings)
    {
        if (settings.Speed is < 0.70f or > 1.00f)
        {
            throw new InvalidDataException("Speed must be between 0.70 and 1.00.");
        }

        if (settings.Reach is < 1.00f or > 1.30f)
        {
            throw new InvalidDataException("Reach must be between 1.00 and 1.30.");
        }

        if (settings.Stagger is < 0.50f or > 1.10f)
        {
            throw new InvalidDataException("Stagger must be between 0.50 and 1.10.");
        }
    }
}
